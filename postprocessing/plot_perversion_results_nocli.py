# 系综平均作图
# ============================================================
def plot_ensemble(group_dir):
    mean_path = group_dir / "ensemble_mean.txt"
    std_path = group_dir / "ensemble_std.txt"

    if not mean_path.exists():
        return

    mean = load_txt(mean_path)
    std = load_txt(std_path) if std_path.exists() else np.zeros_like(mean)

    t = safe_col(mean, 0)
    if t is None:
        print(f"[WARN] 跳过 {mean_path}: 没有 time 列")
        return

    phi_bar = safe_col(mean, 2)
    psi = safe_col(mean, 3)
    n_perv = safe_col(mean, 4)
    avg_dom = safe_col(mean, 5)
    width = safe_col(mean, 6)
    diff = safe_col(mean, 7)
    n_nuc = safe_col(mean, 8)
    n_ann = safe_col(mean, 9)

    s_phi_bar = safe_col(std, 2)
    s_psi = safe_col(std, 3)
    s_n_perv = safe_col(std, 4)
    s_avg_dom = safe_col(std, 5)
    s_width = safe_col(std, 6)
    s_diff = safe_col(std, 7)
    s_n_nuc = safe_col(std, 8)
    s_n_ann = safe_col(std, 9)

    if phi_bar is not None and psi is not None:
        fig, ax = plt.subplots(figsize=(7.2, 4.8))
        ax.plot(t, phi_bar, lw=2, label=r"$\langle|\phi|\rangle$")
        if s_phi_bar is not None:
            ax.fill_between(t, phi_bar - s_phi_bar, phi_bar + s_phi_bar, alpha=0.25)
        ax.plot(t, psi, lw=2, ls="--", label=r"$|\langle\phi\rangle|$")
        if s_psi is not None:
            ax.fill_between(t, psi - s_psi, psi + s_psi, alpha=0.25)
        ax.set_xlabel("Time")
        ax.set_ylabel("Chirality order parameter")
        ax.set_title("Ensemble-averaged chirality")
        ax.legend(frameon=False)
        set_clean_axis(ax)
        savefig(fig, group_dir / "ensemble_order_parameters.png")

    if n_perv is not None:
        fig, ax1 = plt.subplots(figsize=(7.2, 4.8))
        ax1.plot(t, n_perv, lw=2, label=r"$N_{\rm perv}$")
        if s_n_perv is not None:
            ax1.fill_between(t, n_perv - s_n_perv, n_perv + s_n_perv, alpha=0.25)
        ax1.set_xlabel("Time")
        ax1.set_ylabel(r"$N_{\rm perv}$")
        set_clean_axis(ax1)

        if avg_dom is not None:
            ax2 = ax1.twinx()
            ax2.plot(t, avg_dom, lw=2, ls=":", label="Average domain size")
            if s_avg_dom is not None:
                ax2.fill_between(t, avg_dom - s_avg_dom, avg_dom + s_avg_dom, alpha=0.18)
            ax2.set_ylabel("Average domain size")
            ax2.tick_params(direction="in", top=True, right=True)

            lines = ax1.get_lines() + ax2.get_lines()
            labels = [l.get_label() for l in lines]
            ax1.legend(lines, labels, frameon=False, loc="best")
        else:
            ax1.legend(frameon=False)

        ax1.set_title("Ensemble-averaged perversions and coarsening")
        savefig(fig, group_dir / "ensemble_perversions_domains.png")

    if width is not None or diff is not None:
        fig, ax1 = plt.subplots(figsize=(7.2, 4.8))
        lines = []

        if width is not None:
            l1 = ax1.plot(t, width, lw=2, label="Wall width")[0]
            lines.append(l1)
            if s_width is not None:
                ax1.fill_between(t, width - s_width, width + s_width, alpha=0.25)
            ax1.set_ylabel("Wall width")

        ax1.set_xlabel("Time")
        set_clean_axis(ax1)

        if diff is not None:
            ax2 = ax1.twinx()
            l2 = ax2.plot(t, diff, lw=2, ls="--", label=r"$D_{\rm wall}$")[0]
            lines.append(l2)
            if s_diff is not None:
                ax2.fill_between(t, diff - s_diff, diff + s_diff, alpha=0.18)
            ax2.set_ylabel(r"$D_{\rm wall}$")
            ax2.tick_params(direction="in", top=True, right=True)

        labels = [l.get_label() for l in lines]
        ax1.legend(lines, labels, frameon=False, loc="best")
        ax1.set_title("Ensemble-averaged wall kinetics")
        savefig(fig, group_dir / "ensemble_wall_width_diffusion.png")

    if n_nuc is not None and n_ann is not None:
        fig, ax = plt.subplots(figsize=(7.2, 4.8))
        ax.plot(t, n_nuc, lw=2, label="Nucleation")
        if s_n_nuc is not None:
            ax.fill_between(t, n_nuc - s_n_nuc, n_nuc + s_n_nuc, alpha=0.25)
        ax.plot(t, n_ann, lw=2, label="Annihilation")
        if s_n_ann is not None:
            ax.fill_between(t, n_ann - s_n_ann, n_ann + s_n_ann, alpha=0.25)
        ax.set_xlabel("Time")
        ax.set_ylabel("Events per analyzed frame")
        ax.set_title("Ensemble-averaged topological events")
        ax.legend(frameon=False)
        set_clean_axis(ax)
        savefig(fig, group_dir / "ensemble_nucleation_annihilation.png")

    fig, axes = plt.subplots(4, 1, figsize=(7.2, 10.0), sharex=True)

    if phi_bar is not None:
        axes[0].plot(t, phi_bar, lw=1.8, label=r"$\langle|\phi|\rangle$")
        if s_phi_bar is not None:
            axes[0].fill_between(t, phi_bar - s_phi_bar, phi_bar + s_phi_bar, alpha=0.25)
    if psi is not None:
        axes[0].plot(t, psi, lw=1.8, ls="--", label=r"$|\langle\phi\rangle|$")
        if s_psi is not None:
            axes[0].fill_between(t, psi - s_psi, psi + s_psi, alpha=0.18)
    axes[0].set_ylabel("Order")
    axes[0].legend(frameon=False)

    if n_perv is not None:
        axes[1].plot(t, n_perv, lw=1.8)
        if s_n_perv is not None:
            axes[1].fill_between(t, n_perv - s_n_perv, n_perv + s_n_perv, alpha=0.25)
        axes[1].set_ylabel(r"$N_{\rm perv}$")

    if avg_dom is not None:
        axes[2].plot(t, avg_dom, lw=1.8)
        if s_avg_dom is not None:
            axes[2].fill_between(t, avg_dom - s_avg_dom, avg_dom + s_avg_dom, alpha=0.25)
        axes[2].set_ylabel("Domain size")

    if n_nuc is not None:
        axes[3].plot(t, n_nuc, lw=1.5, label="Nucleation")
    if n_ann is not None:
        axes[3].plot(t, n_ann, lw=1.5, label="Annihilation")
    axes[3].set_ylabel("Events")
    axes[3].legend(frameon=False)

    axes[-1].set_xlabel("Time")
    for ax in axes:
        set_clean_axis(ax)
    fig.suptitle(group_dir.name)
    savefig(fig, group_dir / "ensemble_summary.png")

    print(f"[OK] 系综平均图已保存: {group_dir}")


# ============================================================
# 主程序
# ============================================================
if __name__ == "__main__":
    root_str = ROOT_DIR.strip()
    if (not root_str) and USE_FOLDER_DIALOG:
        root_str = pick_folder_by_dialog()

    if not root_str:
        raise SystemExit("请在脚本顶部设置 ROOT_DIR，或者使用弹窗选择 analysis_out 文件夹。")

    root = Path(root_str).expanduser().resolve()
    if not root.is_dir():
        raise NotADirectoryError(f"ROOT_DIR 不存在: {root}")

    print(f"[INFO] ROOT_DIR = {root}")

    if RECURSIVE:
        single_files = sorted(root.rglob("kzm_kinetics_robust.txt"))
        ensemble_dirs = sorted({p.parent for p in root.rglob("ensemble_mean.txt")})
    else:
        single_files = sorted(root.glob("kzm_kinetics_robust.txt"))
        ensemble_dirs = sorted({p.parent for p in root.glob("ensemble_mean.txt")})

    print(f"[INFO] 找到 {len(single_files)} 个单条轨迹数据文件")
    for p in single_files:
        try:
            plot_single_trajectory(p)
        except Exception as e:
            print(f"[ERROR] 单条轨迹作图失败 {p}: {e}")

    print(f"[INFO] 找到 {len(ensemble_dirs)} 个系综平均目录")
    for d in ensemble_dirs:
        try:
            plot_ensemble(d)
        except Exception as e:
            print(f"[ERROR] 系综作图失败 {d}: {e}")

    print("[DONE] 所有图已生成。")
