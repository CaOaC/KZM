#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Plot results generated by batch_perversion_gpu_only_checked_v2.py.

用法：
1. 修改下面的 ROOT_DIR 为 analysis_out 所在目录；
2. 直接运行本脚本；
3. 脚本会递归寻找：
   - kzm_kinetics_robust.txt
   - ensemble_mean.txt
   - ensemble_std.txt
4. 图片会保存到对应 txt 文件所在目录。
"""

from pathlib import Path
import numpy as np
import matplotlib.pyplot as plt


# ============================================================
# 用户配置区
# ============================================================
ROOT_DIR = r"H:\phasediagram\totalTraj\analysis_out"   # 例如 r"G:\chromosome\domainwall\analysis_out"
USE_FOLDER_DIALOG = True

SHOW_FIGURES = False
FIG_DPI = 300
RECURSIVE = True


# ============================================================
# 工具函数
# ============================================================
def pick_folder_by_dialog():
    try:
        import tkinter as tk
        from tkinter import filedialog
        root = tk.Tk()
        root.withdraw()
        folder = filedialog.askdirectory(title="选择 analysis_out 文件夹")
        root.destroy()
        return folder
    except Exception as e:
        print(f"[WARN] 无法打开文件夹选择窗口: {e}")
        return ""


def load_txt(path):
    arr = np.loadtxt(path, comments="#")
    if arr.ndim == 1:
        arr = arr.reshape(1, -1)
    return arr


def safe_col(arr, idx):
    if arr.shape[1] <= idx:
        return None
    return arr[:, idx]


def set_clean_axis(ax):
    ax.tick_params(direction="in", top=True, right=True)
    ax.grid(alpha=0.25)


def savefig(fig, path):
    fig.tight_layout()
    fig.savefig(path, dpi=FIG_DPI, bbox_inches="tight")
    if SHOW_FIGURES:
        plt.show()
    else:
        plt.close(fig)


# ============================================================
# 单条 trajectory 作图
# ============================================================
def plot_single_trajectory(txt_path):
    arr = load_txt(txt_path)
    outdir = txt_path.parent

    t = safe_col(arr, 0)
    phi_bar = safe_col(arr, 2)
    psi = safe_col(arr, 3)
    n_perv = safe_col(arr, 4)
    avg_dom = safe_col(arr, 5)
    width = safe_col(arr, 6)
    diff = safe_col(arr, 7)
    n_nuc = safe_col(arr, 8)
    n_ann = safe_col(arr, 9)

    if t is None:
        print(f"[WARN] 跳过 {txt_path}: 没有 time 列")
        return

    if phi_bar is not None and psi is not None:
        fig, ax = plt.subplots(figsize=(7.2, 4.8))
        ax.plot(t, phi_bar, lw=2, label=r"$\langle|\phi|\rangle$")
        ax.plot(t, psi, lw=2, ls="--", label=r"$|\langle\phi\rangle|$")
        ax.set_xlabel("Time")
        ax.set_ylabel("Chirality order parameter")
        ax.set_title("Local and global chirality")
        ax.legend(frameon=False)
        set_clean_axis(ax)
        savefig(fig, outdir / "plot_order_parameters.png")

    if n_perv is not None:
        fig, ax1 = plt.subplots(figsize=(7.2, 4.8))
        ax1.plot(t, n_perv, lw=2, label="Number of perversions")
        ax1.set_xlabel("Time")
        ax1.set_ylabel(r"$N_{\rm perv}$")
        set_clean_axis(ax1)

        if avg_dom is not None:
            ax2 = ax1.twinx()
            ax2.plot(t, avg_dom, lw=2, ls=":", label="Average domain size")
            ax2.set_ylabel("Average domain size")
            ax2.tick_params(direction="in", top=True, right=True)

            lines = ax1.get_lines() + ax2.get_lines()
            labels = [l.get_label() for l in lines]
            ax1.legend(lines, labels, frameon=False, loc="best")
        else:
            ax1.legend(frameon=False)

        ax1.set_title("Perversions and domain coarsening")
        savefig(fig, outdir / "plot_perversions_domains.png")

    if width is not None or diff is not None:
        fig, ax1 = plt.subplots(figsize=(7.2, 4.8))
        lines = []

        if width is not None:
            l1 = ax1.plot(t, width, lw=2, label="Wall width (stable)")[0]
            lines.append(l1)
            ax1.set_ylabel("Wall width")
        ax1.set_xlabel("Time")
        set_clean_axis(ax1)

        if diff is not None:
            ax2 = ax1.twinx()
            l2 = ax2.plot(t, diff, lw=2, ls="--", label="Diffusion coefficient (stable)")[0]
            lines.append(l2)
            ax2.set_ylabel(r"$D_{\rm wall}$")
            ax2.tick_params(direction="in", top=True, right=True)

        labels = [l.get_label() for l in lines]
        ax1.legend(lines, labels, frameon=False, loc="best")
        ax1.set_title("Stable domain-wall kinetics")
        savefig(fig, outdir / "plot_wall_width_diffusion.png")

    if n_nuc is not None and n_ann is not None:
        fig, ax = plt.subplots(figsize=(7.2, 4.8))
        if len(t) > 1:
            bar_w = 0.8 * np.median(np.diff(t))
        else:
            bar_w = 1.0
        ax.bar(t, n_nuc, width=bar_w, alpha=0.65, label="Nucleation")
        ax.bar(t, -n_ann, width=bar_w, alpha=0.65, label="Annihilation")
        ax.axhline(0, lw=1)
        ax.set_xlabel("Time")
        ax.set_ylabel("Events per analyzed frame")
        ax.set_title("Domain-wall nucleation and annihilation")
        ax.legend(frameon=False)
        set_clean_axis(ax)
        savefig(fig, outdir / "plot_nucleation_annihilation.png")

    fig, axes = plt.subplots(4, 1, figsize=(7.2, 10.0), sharex=True)

    if phi_bar is not None and psi is not None:
        axes[0].plot(t, phi_bar, lw=1.8, label=r"$\langle|\phi|\rangle$")
        axes[0].plot(t, psi, lw=1.8, ls="--", label=r"$|\langle\phi\rangle|$")
        axes[0].set_ylabel("Order")
        axes[0].legend(frameon=False)

    if n_perv is not None:
        axes[1].plot(t, n_perv, lw=1.8)
        axes[1].set_ylabel(r"$N_{\rm perv}$")

    if avg_dom is not None:
        axes[2].plot(t, avg_dom, lw=1.8)
        axes[2].set_ylabel("Domain size")

    if n_nuc is not None and n_ann is not None:
        axes[3].plot(t, n_nuc, lw=1.5, label="Nucleation")
        axes[3].plot(t, n_ann, lw=1.5, label="Annihilation")
        axes[3].set_ylabel("Events")
        axes[3].legend(frameon=False)

    axes[-1].set_xlabel("Time")
    for ax in axes:
        set_clean_axis(ax)
    fig.suptitle(outdir.name)
    savefig(fig, outdir / "plot_summary_single_trajectory.png")

    print(f"[OK] 单条轨迹图已保存: {outdir}")


